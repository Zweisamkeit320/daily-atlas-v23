"use strict";

const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const CHECK_ONLY = process.argv.includes("--check");
const BUNDLES = Object.freeze({
  "runtime-foundation.js": Object.freeze(["state.js", "profile.js", "lock.js", "backup-crypto.js"]),
  "runtime-features.js": Object.freeze([
    "backup.js", "appearance.js", "explore.js", "weekly.js", "music.js", "speech.js",
    "city-live.js", "reminders.js", "visuals.js", "pwa.js"
  ])
});

function assert(condition, message) {
  if (!condition) throw new Error(message);
}

function sourcePath(name) {
  const resolved = path.resolve(ROOT, name);
  assert(resolved.startsWith(`${ROOT}${path.sep}`), `runtime source leaves project root: ${name}`);
  assert(fs.existsSync(resolved) && fs.statSync(resolved).isFile(), `runtime source is missing: ${name}`);
  return resolved;
}

function renderBundle(output, sources) {
  const banner = `/* Generated by scripts/build-runtime-bundles.cjs. Sources: ${sources.join(", ")} */\n`;
  const body = sources.map((name) => {
    const source = fs.readFileSync(sourcePath(name), "utf8").replace(/\r\n/g, "\n").trimEnd();
    return `/* ${name} */\n${source}`;
  }).join("\n\n");
  return `${banner}${body}\n`;
}

function run() {
  for (const [output, sources] of Object.entries(BUNDLES)) {
    const expected = renderBundle(output, sources);
    const target = path.join(ROOT, output);
    if (CHECK_ONLY) {
      assert(fs.existsSync(target), `${output} is missing; run npm run build:runtime`);
      const current = fs.readFileSync(target, "utf8").replace(/\r\n/g, "\n");
      assert(current === expected, `${output} is stale; run npm run build:runtime`);
    } else {
      fs.writeFileSync(target, expected, "utf8");
    }
  }
  console.log(`PASS: runtime bundles ${CHECK_ONLY ? "match" : "built from"} ${Object.values(BUNDLES).flat().length} source modules`);
}

if (require.main === module) run();

module.exports = Object.freeze({ BUNDLES, renderBundle, run });
